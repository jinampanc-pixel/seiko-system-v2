const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'msedge'});
 const page=await browser.newPage({viewport:{width:1400,height:1000}});
 const errors=[]; page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5176/tests/packing-browser/index.html');
 await page.locator('.physicalPackageSummary:not(.physicalInfo)').getByRole('button',{name:'Customize',exact:true}).click();
 for(const name of ['Kurti','Vest','T-Shirt','Track Pant']) await page.locator('.physicalProductChoices label').filter({has:page.locator('b',{hasText:new RegExp(`^${name}$`)})}).getByRole('checkbox').uncheck();
 assert.match(await page.locator('.physicalDrawer footer').innerText(),/63 eligible labels/);
 assert.match(await page.locator('.physicalProductChoices').innerText(),/87 pieces · 63 people/);
 await page.getByRole('button',{name:'Apply',exact:true}).click();
 assert.match(await page.locator('.physicalPreviewNav').innerText(),/1 of 63/);
 assert.match(await page.locator('.physicalRecords h3').innerText(),/63 labels selected/);
 assert.ok(await page.locator('.physicalRecord').count()<=12);
 await page.locator('.physicalRecord input').first().uncheck();
 assert.match(await page.locator('.physicalRecords h3').innerText(),/62 labels selected/);
 assert.match(await page.locator('.physicalRecords p').innerText(),/63 eligible people/);
 await page.getByRole('button',{name:'Select all',exact:true}).click();
 await page.getByRole('textbox',{name:'Find label records'}).fill('Person 1');
 assert.ok(await page.locator('.physicalRecord').count()<=12);
 await page.getByRole('textbox',{name:'Find label records'}).fill('');
 // Cancel is a transaction: the applied eligible set must not change.
 await page.locator('.physicalPackageSummary:not(.physicalInfo)').getByRole('button',{name:'Customize',exact:true}).click();
 await page.locator('.physicalProductChoices label').filter({has:page.locator('b',{hasText:/^Shirt$/})}).getByRole('checkbox').uncheck();
 await page.locator('.physicalDrawer footer').getByRole('button',{name:'Cancel'}).click();
 assert.match(await page.locator('.physicalRecords h3').innerText(),/63 labels selected/);
 await page.getByRole('button',{name:'Customize label information',exact:true}).click();
 await page.locator('.physicalFieldToggle').filter({hasText:'Label number / total'}).getByRole('checkbox').check();
 await page.getByRole('dialog',{name:'Customize label information',exact:true}).getByRole('button',{name:'Apply',exact:true}).click();
 const item=page.locator('.physicalItem').first(); await item.click();
 const x=page.getByRole('spinbutton',{name:'x',exact:true}); const before=Number(await x.inputValue());
 await item.press('ArrowRight'); assert.equal(Number(await x.inputValue()),before+1);
 await page.getByRole('button',{name:'Undo',exact:true}).click(); assert.equal(Number(await x.inputValue()),before);
 await page.getByRole('button',{name:'Redo',exact:true}).click(); assert.equal(Number(await x.inputValue()),before+1);
 await page.getByRole('combobox',{name:'Canvas zoom'}).selectOption('2');
 let box=await item.boundingBox(); await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down(); await page.mouse.move(box.x+box.width/2+16,box.y+box.height/2+8,{steps:4}); await page.mouse.up();
 assert.ok(Number(await x.inputValue())>=before+2);
 const moved=Number(await x.inputValue()); await page.getByRole('button',{name:'Undo',exact:true}).click(); assert.equal(Number(await x.inputValue()),before+1); await page.getByRole('button',{name:'Redo',exact:true}).click(); assert.equal(Number(await x.inputValue()),moved);
 const width=page.getByRole('spinbutton',{name:'w',exact:true}); const widthBefore=Number(await width.inputValue());
 box=await page.locator('.handle-se').boundingBox(); await page.mouse.move(box.x+box.width/2,box.y+box.height/2); await page.mouse.down(); await page.mouse.move(box.x+box.width/2+16,box.y+box.height/2+8,{steps:4}); await page.mouse.up(); assert.ok(Number(await width.inputValue())>widthBefore);
 await x.fill('100'); await x.press('Tab'); assert.ok(Number(await x.inputValue())+Number(await width.inputValue())<=50);
 await page.getByRole('button',{name:'Auto-arrange'}).click();
 await page.getByRole('button',{name:'Fit',exact:true}).click();
 const preview=await page.locator('.physicalCanvas .physicalText').allTextContents();
 await page.getByRole('button',{name:'Print / PDF (63)',exact:true}).click();
 await page.waitForFunction(()=>window.printCalls===1);
 assert.equal(await page.locator('.physicalPrintedLabel').count(),63);
 const printed=await page.locator('.physicalPrintedLabel').first().locator('.physicalText').allTextContents(); assert.deepEqual(printed,preview);
 assert.match(printed.join(' '),/1 of 63/);
 const styles=await page.locator('.physicalPrintedLabel').first().locator('.physicalText').evaluateAll(nodes=>nodes.map(node=>({font:node.style.fontSize,align:node.style.textAlign})));
 const previewStyles=await page.locator('.physicalCanvas .physicalText').evaluateAll(nodes=>nodes.map(node=>({font:node.style.fontSize,align:node.style.textAlign}))); assert.deepEqual(styles,previewStyles);
 // Every printed glyph uses the same SVG geometry as the canvas.
 const screenSvg=await page.locator('.physicalCanvas .physicalText svg').evaluateAll(nodes=>nodes.map(n=>n.outerHTML));
 const printSvg=await page.locator('.physicalPrintedLabel').first().locator('.physicalText svg').evaluateAll(nodes=>nodes.map(n=>n.outerHTML));
 assert.deepEqual(printSvg,screenSvg);
 await page.screenshot({path:'work/label-editor-verified.png',fullPage:true});
 await page.pdf({path:'work/label-output-verified.pdf',preferCSSPageSize:true,printBackground:true});
 const pdf=fs.readFileSync('work/label-output-verified.pdf').toString('latin1');
 const media=pdf.match(/\/MediaBox\s*\[\s*0\s+0\s+([\d.]+)\s+([\d.]+)\s*\]/);
 assert.ok(media,'PDF has a physical page box');
 assert.ok(Math.abs(Number(media[1])*25.4/72-50)<.3,'50 mm single-label page');
 assert.ok(Math.abs(Number(media[2])*25.4/72-25)<.3,'25 mm label height');
 assert.equal((pdf.match(/\/Type\s*\/Page\b/g)||[]).length,63);
 // A real saved task restores its manual selections as well as product rules.
 await page.locator('.physicalRecord input').first().uncheck();
 await page.getByRole('button',{name:'Save label set',exact:true}).click();
 await page.evaluate(()=>sessionStorage.setItem('jinam:seiko:labels:open-task',JSON.parse(localStorage.getItem('jinam:seiko:labels:tasks-v1'))[0].id));
 await page.reload();
 await page.waitForSelector('.physicalRecords h3');
 assert.match(await page.locator('.physicalRecords h3').innerText(),/62 labels selected/);
 await page.getByRole('textbox',{name:'Find label records'}).fill('Person 1');
 const fixture=JSON.parse(fs.readFileSync('tests/fixtures/packing-quantity-regression.json'));
 const expected=fixture.quantities.filter((q,i)=>q[0]>0&&q[2]>0&&`Person ${i+1}`.toLowerCase().includes('person 1')).length;
 assert.match(await page.locator('.physicalRecords>small').innerText(),new RegExp(`^${expected} matching`));
 await page.getByRole('textbox',{name:'Find label records'}).fill('');
 await page.locator('.physicalPackageSummary:not(.physicalInfo)').getByRole('button',{name:'Customize',exact:true}).click();
 await page.locator('.physicalProductChoices label').filter({has:page.locator('b',{hasText:/^Shirt$/})}).getByRole('checkbox').uncheck();
 const pants=fixture.quantities.filter(q=>q[0]>0).length;
 assert.match(await page.locator('.physicalDrawer footer').innerText(),new RegExp(`${pants} eligible labels`));
 await page.getByRole('button',{name:'Apply',exact:true}).click();
 assert.match(await page.locator('.physicalRecords h3').innerText(),new RegExp(`${pants} labels selected`));
 assert.match(await page.locator('.physicalPreviewNav').innerText(),new RegExp(`1 of ${pants}`));
 await page.setViewportSize({width:480,height:900});
 assert.ok(await page.locator('.physicalCanvas').evaluate(el=>el.getBoundingClientRect().width<480));
 // Saved print route must reconcile a legacy set containing all source IDs.
 const taskId=await page.evaluate(()=>{
   const tasks=JSON.parse(localStorage.getItem('jinam:seiko:labels:tasks-v1'));
   tasks[0].selectedRows=JSON.parse(localStorage.getItem('jinam:seiko:orders-v1'))[0].records.map(record=>record.recordId);
   localStorage.setItem('jinam:seiko:labels:tasks-v1',JSON.stringify(tasks));return tasks[0].id;
 });
 await page.goto(`http://127.0.0.1:5176/tests/packing-browser/index.html?task=${taskId}&business=seiko&mode=pdf`);
 await page.waitForFunction(()=>window.printCalls===1);
 assert.equal(await page.locator('.physicalPrintedLabel').count(),63);
 assert.match(await page.locator('.savedPrintStatus').innerText(),/63 labels/);
 assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('jinam:seiko:labels:pdf-records-v1'))[0].labelCount),63);
 // The real route returns to its opener after printing. Keep the test page alive
 // until Chromium has returned the PDF bytes to the automation client.
 await page.evaluate(()=>{history.back=()=>{};});
 await page.pdf({path:'work/saved-label-output-verified.pdf',preferCSSPageSize:true,printBackground:true});
 const savedPdf=fs.readFileSync('work/saved-label-output-verified.pdf').toString('latin1');
 assert.equal((savedPdf.match(/\/Type\s*\/Page\b/g)||[]).length,63);
 assert.deepEqual(errors,[]);
 console.log('PASS: 63 eligible, AND counts, manual selection, search, Cancel, numbering, virtualization, keyboard, undo/redo, drag, resize, bounds, zoom, preview/print parity, PDF.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});

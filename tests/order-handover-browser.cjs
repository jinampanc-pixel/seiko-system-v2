const assert = require('node:assert/strict');
module.exports = async ({ page, sqlite, order, seed, navigate }) => {
  const sample = structuredClone(order);
  sample.orderId = 'handover-order'; sample.details.orderNo = 'HANDOVER-001'; sample.details.clientName = 'Handover test school';
  sample.measurements = [{id:'length',name:'Length',type:'number',appliesTo:['vest'],requiredMode:'Optional'}];
  sample.products[0].specifications = [{id:'colour',name:'Colour',role:'colour',mode:'same_for_all',defaultValue:'Blue',groupRules:[],attachments:[],required:false}];
  sample.records = Array.from({length:101}, (_, index) => ({recordId:`handover-${index}`,personId:`P-${index}`,values:{'field:name':`Student ${index+1}`,'product:vest:qty':2,'measurement:length:product:vest':30}}));
  await seed(sample); await page.reload(); await navigate('Orders');
  const doc={id:'handover-invoice',kind:'invoice',orderId:sample.orderId,orderNo:sample.details.orderNo,clientName:sample.details.clientName,issueDate:'2026-10-13',taxMode:'non_gst',taxTreatment:'intra_state',lines:[{id:'line',description:'Vest',quantity:202,unitRate:70,taxRate:0}],status:'issued',createdAt:'2026-10-13',updatedAt:'2026-10-13'};
  sqlite.prepare('INSERT INTO seiko_billing_documents(id,data,total_paise,created_by) VALUES(?,?,?,?)').run(doc.id,JSON.stringify(doc),1414000,'owner');
  await page.getByPlaceholder('Search order, client, type or status').fill('HANDOVER-001');
  const row = page.locator('.orderRow').filter({hasText:'HANDOVER-001'});
  await row.locator('summary').click();
  await row.getByRole('button',{name:'Student handover list / PDF',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'Student handover list',exact:true});
  const preview=page.frameLocator('iframe[title="Student handover print preview"]');
  await preview.locator('tr[data-record-id]').last().waitFor();
  assert.equal(await preview.locator('tr[data-record-id]').count(),101);
  assert.match(await preview.locator('body').innerText(),/202|Student 101/);
  assert.doesNotMatch(await preview.locator('body').innerText(),/Length: 30|Colour: Blue/);
  await dialog.getByLabel('Sizes / measurements',{exact:true}).check();
  await dialog.getByLabel('Product specifications',{exact:true}).check();
  await preview.getByText('Length: 30',{exact:true}).first().waitFor();
  assert.match(await preview.locator('body').innerText(),/Colour: Blue/);
  await dialog.getByLabel('Financial reference',{exact:true}).check();
  await dialog.getByLabel('Billing document').waitFor();
  assert.equal(await dialog.getByRole('button',{name:'Print / Save PDF',exact:true}).isEnabled(),false,'Unselected financial data cannot silently print');
  await dialog.getByLabel('Billing document').selectOption(doc.id);
  await preview.getByText('Financial reference -',{exact:false}).waitFor();
  assert.match(await preview.locator('body').innerText(),/₹14,140.00/);
  await dialog.getByLabel('Financial reference',{exact:true}).uncheck();
  for(const width of [1365,390]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await dialog.isVisible(),true);
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  }
  await dialog.getByRole('button',{name:'Close preview'}).click();
  await page.setViewportSize({width:1365,height:900});
  await page.getByPlaceholder('Search order, client, type or status').fill('Student 1');
  await row.locator('summary').click();await row.getByRole('button',{name:'Student handover list / PDF',exact:true}).click();
  await preview.locator('tr[data-record-id]').last().waitFor();
  assert.equal(await preview.locator('tr[data-record-id]').count(),101,'Order search does not trim print rows');
  await dialog.getByRole('button',{name:'Print / Save PDF'}).waitFor({state:'visible'});
  assert.equal(await dialog.getByRole('button',{name:'Print / Save PDF'}).isEnabled(),true);
  const iframe=page.frames().find(frame=>frame!==page.mainFrame()&&frame.url()==='about:srcdoc');
  await iframe.evaluate(()=>{window.print=()=>{document.body.dataset.printed='yes';};});
  await dialog.getByRole('button',{name:'Print / Save PDF'}).click();
  assert.equal(await preview.locator('body').getAttribute('data-printed'),'yes','Print button prints the complete report iframe');
  const stored=JSON.parse(sqlite.prepare('SELECT document_json FROM erp_orders WHERE id=?').get(sample.orderId).document_json);
  assert.equal(stored.status,'Active'); assert.equal(stored.records.length,101,'Preview never mutates order data');
  await dialog.getByRole('button',{name:'Close preview'}).click();
  console.log('PASS: configurable handover preview, all rows, sizes/specs, financial selection guard, desktop/mobile and no delivery mutation.');
};
